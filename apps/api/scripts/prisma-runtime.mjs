#!/usr/bin/env node
/**
 * Prisma 多数据库兼容入口。
 *
 * 默认 schema.prisma 为 PostgreSQL（保留原生数组）。
 * 当 DATABASE_URL 指向 SQLite / MySQL 时，会从 schema.prisma 生成
 * schema.<provider>.prisma，把标量数组字段改写为 Json 以兼容这两种数据库。
 *
 * 用法：node scripts/prisma-runtime.mjs <generate|push|migrate|deploy|studio>
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const prismaDir = path.join(appDir, 'prisma')
const baseSchema = path.join(prismaDir, 'schema.prisma')

function loadDotEnv() {
  const envPath = path.join(appDir, '.env')
  if (!fs.existsSync(envPath)) {
    return
  }
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/)
    if (!match) {
      continue
    }
    let value = match[2].trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    if (process.env[match[1]] === undefined) {
      process.env[match[1]] = value
    }
  }
}

function detectProvider(url) {
  const override = process.env.DB_PROVIDER?.trim()
  if (override) {
    if (!['sqlite', 'mysql', 'postgresql'].includes(override)) {
      throw new Error(`DB_PROVIDER 仅支持 sqlite / mysql / postgresql，当前为 ${override}`)
    }
    return override
  }
  if (!url || url.startsWith('file:')) {
    return 'sqlite'
  }
  if (url.startsWith('mysql://')) {
    return 'mysql'
  }
  if (url.startsWith('postgresql://') || url.startsWith('postgres://')) {
    return 'postgresql'
  }
  throw new Error(`无法从 DATABASE_URL 识别数据库类型：${url.split(':')[0]}://`)
}

/** 标量数组在 SQLite / MySQL 中不被 Prisma 支持，改写为 Json（默认值 [] → "[]"） */
function rewriteScalarLists(schema) {
  const scalarTypes = 'String|Role|Int|Float|Boolean|DateTime|Json|Decimal|BigInt|Bytes'
  let replaced = 0
  const lines = schema.split(/\r?\n/).map((line) =>
    line.replace(
      new RegExp(`^(\\s+\\w+\\s+)(${scalarTypes})\\[\\](\\s+@default\\(\\[\\]\\))?`),
      (_match, prefix, _type, defaultClause) => {
        replaced += 1
        return defaultClause ? `${prefix}Json @default("[]")` : `${prefix}Json`
      },
    ),
  )
  if (replaced === 0) {
    throw new Error('未找到需要改写的标量数组字段，请检查 schema.prisma')
  }
  const rest = lines.find((line) => new RegExp(`\\b(${scalarTypes})\\[\\]`).test(line))
  if (rest) {
    throw new Error(`仍存在未改写的标量数组字段：${rest.trim()}`)
  }
  return { schema: lines.join('\n'), replaced }
}

function prepareSchema(provider) {
  const canonical = fs.readFileSync(baseSchema, 'utf8')
  if (provider === 'postgresql') {
    return baseSchema
  }
  if (!canonical.includes('provider = "postgresql"')) {
    throw new Error('schema.prisma 未使用 provider = "postgresql"，无法生成方言 Schema')
  }
  // 去掉基准 Schema 顶部注释，避免派生文件里出现“本文件为 PostgreSQL”的误导说明
  const canonicalBody = canonical.replace(/^(?:[ \t]*\/\/[^\n]*\n)+/, '')
  const rewritten = rewriteScalarLists(canonicalBody)
  const dialectSchema = rewritten.schema.replace(
    'provider = "postgresql"',
    `provider = "${provider}"`,
  )
  const header = [
    `// AUTO-GENERATED by scripts/prisma-runtime.mjs from schema.prisma for ${provider}.`,
    `// Scalar list fields are stored as Json (${rewritten.replaced} fields). Do not edit.`,
  ].join('\n')
  const target = path.join(prismaDir, `schema.${provider}.prisma`)
  fs.writeFileSync(target, `${header}\n${dialectSchema}\n`)
  return target
}

function runPrisma(args) {
  const prismaBin = path.join(
    appDir,
    'node_modules',
    '.bin',
    process.platform === 'win32' ? 'prisma.cmd' : 'prisma',
  )
  const bin = fs.existsSync(prismaBin) ? prismaBin : 'prisma'
  const result = spawnSync(bin, args, {
    cwd: appDir,
    stdio: 'inherit',
    env: process.env,
  })
  if (result.error) {
    throw result.error
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1)
  }
}

function main() {
  loadDotEnv()
  const url = process.env.DATABASE_URL
  if (!url) {
    throw new Error('缺少 DATABASE_URL，请在 apps/api/.env 中配置（默认 file:./dev.db）')
  }
  const provider = detectProvider(url)
  const schema = prepareSchema(provider)
  const command = process.argv[2] ?? 'generate'
  const extraArgs = process.argv.slice(3)
  console.log(`[prisma] provider=${provider} schema=${path.relative(appDir, schema)}`)

  switch (command) {
    case 'generate':
      runPrisma(['generate', '--schema', schema, ...extraArgs])
      break
    case 'push':
      runPrisma(['generate', '--schema', schema])
      runPrisma(['db', 'push', '--schema', schema, '--skip-generate', ...extraArgs])
      break
    case 'migrate':
      if (provider === 'postgresql') {
        runPrisma(['migrate', 'dev', '--schema', schema, ...extraArgs])
      } else {
        console.log('[prisma] 非 PostgreSQL 使用 db push（SQLite/MySQL 不维护迁移历史）')
        runPrisma(['generate', '--schema', schema])
        runPrisma(['db', 'push', '--schema', schema, '--skip-generate', ...extraArgs])
      }
      break
    case 'deploy':
      if (provider === 'postgresql') {
        runPrisma(['migrate', 'deploy', '--schema', schema, ...extraArgs])
      } else {
        runPrisma(['generate', '--schema', schema])
        runPrisma(['db', 'push', '--schema', schema, '--skip-generate', ...extraArgs])
      }
      break
    case 'studio':
      runPrisma(['studio', '--schema', schema, ...extraArgs])
      break
    default:
      throw new Error(`未知命令：${command}（支持 generate / push / migrate / deploy / studio）`)
  }
}

try {
  main()
} catch (error) {
  console.error(`[prisma] ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
